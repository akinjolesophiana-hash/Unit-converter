def m_to_km(num):
    kilometer = num /1000
    return kilometer

def m_to_cm(num):
    centimeter = num * 100
    return centimeter

def cm_to_m(num):
    meter = num / 100
    return meter

def cm_to_mm(num):
    millimeter = num * 10
    return millimeter

def mm_to_cm(num):
    centimeter = num / 10
    return centimeter

def miles_to_km(num):
    kilometer = num * 1.60934
    return kilometer

def km_to_miles(num):
    miles = num / 1.60934
    return miles

def inches_to_cm(num):
    centimeter = num * 2.54
    return centimeter

def cm_to_inches(num):
    inches = num / 2.54
    return inches